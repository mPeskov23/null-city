"""Compile reviewed source/English/Spanish catalogs, including HTML text fragments.
No network translation or runtime dependency. Run from any working directory.
"""
import json
from pathlib import Path
from html.parser import HTMLParser
ROOT=Path(__file__).resolve().parents[2]
source=json.loads((ROOT/'locales/source.json').read_text())
catalog={}
class Fragments(HTMLParser):
    def __init__(self,text):
        super().__init__();self.parts=[];self.feed(text)
    def handle_data(self,text):
        if text.strip(): self.parts.append(text)
def add(key,en,es):
    if not key.strip(): return
    catalog.setdefault(key,[en,es])
    catalog.setdefault(key.strip(),[en.strip(),es.strip()])
for group,keys in source.items():
    if not keys: continue
    lines=(ROOT/f'locales/{group}.txt').read_text().splitlines()
    if len(lines)!=len(keys): raise ValueError(f'{group}: {len(lines)} translations for {len(keys)} sources')
    for i,(key,line) in enumerate(zip(keys,lines)):
        pair=line.split('|')
        if len(pair)!=2 or any(not value.strip() for value in pair): raise ValueError(f'{group}:{i}: expected English|Spanish')
        en,es=[s.replace('\\n','\n') for s in pair]
        add(key,en,es)
        # Rich text is authored in source, not injected by the translator.
        if '<' in key and '>' in key:
            parts=[Fragments(s).parts for s in [key,en,es]]
            if len(parts[0])==len(parts[1])==len(parts[2]):
                for a,b,c in zip(*parts): add(a,b,c)
        if '\n' in key:
            parts=[s.split('\n') for s in [key,en,es]]
            if len(parts[0])==len(parts[1])==len(parts[2]):
                for a,b,c in zip(*parts): add(a,b,c)
extra=json.loads((ROOT/'locales/extra.json').read_text())
for k,v in extra.items(): add(k,*v)
for k,v in list(catalog.items()):
    if k.upper()!=k: catalog.setdefault(k.upper(),[s.upper() for s in v])
output='// Generated by scripts/i18n/build.py; edit locales, not this file.\n'+'globalThis.NULL_CITY_MESSAGES='+json.dumps(catalog,ensure_ascii=False,separators=(',',':'))+';\n'
(ROOT/'src/i18n-catalog.js').write_text(output)
print(f'Compiled {len(catalog)} translation entries in three languages.')
